const workGallery = document.querySelector('.work-gallery');
const workTemplate = document.querySelector('#work-card-template');

if (workGallery && workTemplate) {
  for (const project of projects) {
    const card = workTemplate.content.cloneNode(true);
    const link = card.querySelector('.work-open');
    link.href = `./proyecto.html?id=${project.id}`;
    card.querySelector('img').src = project.image;
    card.querySelector('strong').textContent = project.title;
    card.querySelector('small').textContent = `${project.subtitle} · ${project.category} · ${project.year}`;
    workGallery.append(card);
  }
}

const projectDetail = document.querySelector('#project-detail');

if (projectDetail) {
  const id = new URLSearchParams(window.location.search).get('id');
  const project = projects.find(({ id: projectId }) => String(projectId) === id);

  if (project) {
    document.title = `${project.title} | Amarg* Obrero`;
    document.querySelector('#project-kicker').textContent = `${project.category} · ${project.year}`;
    document.querySelector('#project-title').textContent = project.title;
    document.querySelector('#project-subtitle').textContent = project.subtitle;
    document.querySelector('#project-description').textContent = project.description;

    if (project.boards.length) {
      const images = project.boards;
      const gallery = document.querySelector('#project-gallery');
      const cover = document.querySelector('#project-cover');
      const controls = document.querySelector('#gallery-controls');
      const count = document.querySelector('#gallery-count');
      const openLightbox = document.querySelector('#project-open-lightbox');
      const lightbox = document.querySelector('#project-lightbox');
      const lightboxImage = document.querySelector('#lightbox-image');
      const lightboxCount = document.querySelector('#lightbox-count');
      const lightboxPrev = document.querySelector('#lightbox-prev');
      const lightboxNext = document.querySelector('#lightbox-next');
      let imageIndex = 0;

      function showImage(step) {
        imageIndex = (imageIndex + step + images.length) % images.length;
        cover.alt = `Pieza ${imageIndex + 1} de ${project.title}`;
        cover.src = images[imageIndex];
        count.textContent = `${imageIndex + 1} de ${images.length}`;

        // El visor ampliado sigue la imagen elegida en la galería.
        if (lightbox.open) {
          lightboxImage.src = images[imageIndex];
          lightboxImage.alt = cover.alt;
          lightboxCount.textContent = `${imageIndex + 1} de ${images.length}`;
        }
      }

      showImage(0);
      gallery.hidden = false;

      openLightbox.addEventListener('click', () => {
        lightbox.showModal();
        showImage(0);
      });

      document.querySelector('#lightbox-close').addEventListener('click', () => lightbox.close());
      lightbox.addEventListener('click', (event) => {
        if (event.target === lightbox) lightbox.close();
      });
      lightbox.addEventListener('keydown', (event) => {
        if (images.length < 2) return;
        if (event.key === 'ArrowLeft' || event.key === 'ArrowRight') {
          event.preventDefault();
          showImage(event.key === 'ArrowLeft' ? -1 : 1);
        }
      });

      if (images.length > 1) {
        gallery.classList.add('has-controls');
        controls.hidden = false;
        lightboxPrev.hidden = false;
        lightboxNext.hidden = false;
        document.querySelector('#gallery-prev').addEventListener('click', () => showImage(-1));
        document.querySelector('#gallery-next').addEventListener('click', () => showImage(1));
        lightboxPrev.addEventListener('click', () => showImage(-1));
        lightboxNext.addEventListener('click', () => showImage(1));
        controls.addEventListener('keydown', (event) => {
          if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight') return;
          event.preventDefault();
          showImage(event.key === 'ArrowLeft' ? -1 : 1);
        });
      }
    }

    if (project.youtube) {
      const video = document.querySelector('#video');
      const player = document.querySelector('#project-player');
      const link = document.querySelector('#project-youtube');

      // Acepta una URL o varias, sin alterar los proyectos que tienen un solo video.
      const urls = Array.isArray(project.youtube)
        ? project.youtube
        : [project.youtube];

      urls.forEach((url, index) => {
        const videoUrl = new URL(url);
        const videoId = videoUrl.hostname.includes('youtu.be')
          ? videoUrl.pathname.slice(1)
          : videoUrl.searchParams.get('v');

        const iframe = index === 0 ? player : player.cloneNode(false);
        const youtubeLink = index === 0 ? link : link.cloneNode(true);

        if (index > 0) {
          iframe.removeAttribute('id');
          youtubeLink.removeAttribute('id');
        }

        iframe.src = `https://www.youtube-nocookie.com/embed/${videoId}`;
        iframe.title = `Video ${index + 1} de ${project.title}`;
        youtubeLink.href = url;
        youtubeLink.textContent = `Abrir video ${index + 1} en YouTube ↗`;

        if (index > 0) video.append(iframe, youtubeLink);
      });

      video.hidden = false;
      document.querySelector('#project-video-link').hidden = !project.boards.length;
    }

    projectDetail.hidden = false;
  } else {
    const status = document.querySelector('#project-status');
    status.textContent = 'No encontramos ese proyecto.';
    status.hidden = false;
  }
}
